from typing import Optional, List, Dict, Any, Union
from langchain_core.tools import tool
import digitalhub as dh


@tool
def new_dh_artifact(
    project: str,
    name: str,
    kind: str = "artifact",
    uuid: Optional[str] = None,
    description: Optional[str] = None,
    labels: Optional[List[str]] = None,
    embedded: bool = False,
    path: Optional[str] = None,
    extensions: Optional[List[dict]] = None,
    extra_specs: Optional[Dict[str, Any]] = None,
    **kwargs: Any,
):
    """
    Create a new Artifact entity in DigitalHub WITHOUT uploading file content.

    Registers a metadata-only reference pointing at an existing local or remote
    path (e.g. an existing s3:// object). 'path' becomes both the artifact's
    spec.path (source of downloads) and the default destination of upload().
    Kind-specific spec fields go inside 'extra_specs'.
    """
    raw_specs = extra_specs or kwargs.get("kwargs") or kwargs.get("v__kwargs") or {}
    if not isinstance(raw_specs, dict):
        raw_specs = {}
    spec_kwargs = {k: v for k, v in raw_specs.items() if k not in ("v__kwargs", "kwargs")}
    return dh.new_artifact(
        project=project,
        name=name,
        kind=kind,
        uuid=uuid,
        description=description,
        labels=labels,
        embedded=embedded,
        path=path,
        extensions=extensions,
        **spec_kwargs,
    )


