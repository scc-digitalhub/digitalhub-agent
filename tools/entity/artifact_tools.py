    """
    Log an artifact: create the entity AND upload the local file(s) to the artifact store.

    'source' can be a single local filepath, a directory, or a list of paths.
    'path' is the destination path in the artifact store; if not provided, it
    is auto-generated by the SDK.
    """
    raw_specs = extra_specs or kwargs.get("kwargs") or kwargs.get("v__kwargs") or {}
    if not isinstance(raw_specs, dict):
        raw_specs = {}
    spec_kwargs = {k: v for k, v in raw_specs.items() if k not in ("v__kwargs", "kwargs")}
    return dh.log_artifact(
        project=project,
        name=name,
        kind=kind,
        source=source,
        drop_existing=drop_existing,
        path=path,
        description=description,
        labels=labels,
        **spec_kwargs,
    )


