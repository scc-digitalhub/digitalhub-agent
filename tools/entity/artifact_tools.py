@tool
def update_dh_artifact(
    project_name: str,
    name: str,
):
    """
    Update an artifact object in the backend. Note that object specs are immutable.
    """
    art = dh.get_artifact(name, project=project_name)
    return dh.update_artifact(art)


@tool
def delete_dh_artifact(
    identifier: str,
    project: Optional[str] = None,
    entity_id: Optional[str] = None,
    delete_all_versions: bool = False,
    cascade: bool = True,
):
    """
    Delete an artifact object from backend.
    """
    return dh.delete_artifact(
        identifier=identifier,
        project=project,
        entity_id=entity_id,
        delete_all_versions=delete_all_versions,
        cascade=cascade,
    )


@tool
def save_dh_artifact(
    project_name: str,
    name: str,
    update: bool = False,
):
    """
    Save or update the artifact entity into the backend.
    """
    art = dh.get_artifact(name, project=project_name)
    return art.save(update=update)


@tool
def refresh_dh_artifact(
    project_name: str,
    name: str,
):
    """
    Refresh artifact state from backend.
    """
    art = dh.get_artifact(name, project=project_name)
    return art.refresh()


@tool
def export_dh_artifact(
    project_name: str,
    name: str,
):
    """
    Export artifact object as a YAML file in the context folder.
    """
    art = dh.get_artifact(name, project=project_name)
    return art.export()


@tool
def as_file_dh_artifact(
    project_name: str,
    name: str,
):
    """
    Download the artifact into a temporary folder and return the list of file paths.

    Useful for immediate consumption (e.g. read/parse) without choosing a destination.
    """
    art = dh.get_artifact(name, project=project_name)
    return art.as_file()


@tool
def download_dh_artifact(
    project_name: str,
    name: str,
    destination: Optional[str] = None,
    overwrite: bool = False,
):
    """
    Download the artifact's file(s) from storage to a local path.

    If 'destination' is not specified, files are placed under the context path.
    If files already exist and overwrite=False, an error is raised.
    """
    art = dh.get_artifact(name, project=project_name)
    return art.download(destination=destination, overwrite=overwrite)


@tool
def upload_dh_artifact(
    project_name: str,
    name: str,
    source: Union[str, List[str]],
    keep_dir_structure: bool = False,
):
    """
    Upload local file(s) to the artifact's spec.path in remote storage.

    'source' can be a filepath, a directory, or a list of paths.
    When 'source' is a directory or list, spec.path must be a folder/partition
    ending with '/' (for s3).
    """
    art = dh.get_artifact(name, project=project_name)
    return art.upload(source, keep_dir_structure=keep_dir_structure)


